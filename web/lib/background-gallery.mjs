export const BACKGROUND_CATEGORIES =
  Object.freeze(['All','Floral','Patterns','Botanical','Playful','Minimal']);

export function filterBackgrounds(occasion='OTHER',category='All'){
  return BACKGROUND_GALLERY
    .filter(b=>category==='All'||b.category===category)
    .sort((a,b)=>{
      const score=x=>x.occasion===occasion?0:x.occasion==='OTHER'?1:2;
      return score(a)-score(b);
    });
}

export function findBackground(id){
  return BACKGROUND_GALLERY.find(b=>b.id===id)||null;
}
